#!/usr/bin/env node
/**
 * Sync public Razorpay Key ID into public/js/env.js from root .env.
 * Never writes the Key Secret into public/.
 *
 * Usage: node scripts/sync-razorpay-env.cjs
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const envPath = path.join(root, ".env");
const outPath = path.join(root, "public", "js", "env.js");

function parseEnv(filePath) {
  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing ${filePath}. Copy .env.example → .env first.`);
  }
  const map = {};
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    map[key] = value;
  }
  return map;
}

const env = parseEnv(envPath);
const keyId = env.RAZORPAY_KEY_ID || "";

if (!keyId || !keyId.startsWith("rzp_")) {
  throw new Error(
    "RAZORPAY_KEY_ID missing or invalid in .env (expected rzp_test_… / rzp_live_…)."
  );
}

if (env.RAZORPAY_KEY_SECRET && keyId.includes(env.RAZORPAY_KEY_SECRET)) {
  throw new Error("Refusing to publish Key Secret into public/js/env.js.");
}

const stamp = new Date().toISOString();
const contents = `/**
 * AUTO-GENERATED by scripts/sync-razorpay-env.cjs — do not edit by hand.
 * Source: repo-root .env → RAZORPAY_KEY_ID only (never KEY_SECRET).
 * Generated: ${stamp}
 *
 * This static Hosting app has no Vite/Next env injection, so the public
 * Key ID is mirrored here for the browser. Backend uses process.env from .env.
 */
export const RAZORPAY_KEY_ID = ${JSON.stringify(keyId)};

/** Cache-bust fingerprint for debugging which key the browser loaded */
export const RAZORPAY_KEY_FINGERPRINT = ${JSON.stringify(
  keyId.slice(0, 12) + "…" + keyId.slice(-4)
)};
`;

fs.writeFileSync(outPath, contents, "utf8");

const functionsEnv = path.join(root, "functions", ".env");
fs.copyFileSync(envPath, functionsEnv);

console.log(
  `Wrote ${path.relative(root, outPath)} → ${keyId.slice(0, 12)}…${keyId.slice(-4)}`
);
console.log("Synced functions/.env from root .env");
